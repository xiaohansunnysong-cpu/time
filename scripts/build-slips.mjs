function extractHandmade() {
  const src = readFileSync(resolve(root, "src/lib/challenges.ts"), "utf8")
  const re =
    /rank:\s*"([^"]+)"\s*,\s*verse:\s*"([^"]+)"\s*,\s*title:\s*"([^"]+)"\s*,\s*description:\s*"([^"]+)"\s*,\s*duration:\s*(\d+)\s*,\s*category:\s*"([^"]+)"/g
  const found = []
  for (const match of src.matchAll(re)) {
    found.push({
      rank: match[1],
      verse: match[2],
      title: match[3],
      description: match[4],
      duration: Number(match[5]),
      category: match[6],
    })
  }
  if (found.length < 90) {
    throw new Error(`手写签只解析到 ${found.length} 支`)
  }
  return found
}

function acceptable(slip) {
  const all = `${slip.title}${slip.description}${slip.verse}`
  if (BAD.test(all)) return false
  if (slip.title.length < 4 || slip.title.length > 22) return false
  if (slip.description.length < 12 || slip.description.length > 96) return false
  if (slip.verse.length < 4 || slip.verse.length > 22) return false
  if (/[A-Za-z{}]/.test(all)) return false
  if (slip.title.includes("○") || slip.description.includes("○")) return false
  return true
}

function build() {
  const handmade = extractHandmade()
  const byTag = new Map()
  for (const item of allItems) {
    const list = byTag.get(item.tag) ?? []
    list.push(item.text)
    byTag.set(item.tag, list)
  }
  const queues = frames.map((template) => {
    const bank = byTag.get(template.tag) ?? []
    return bank.map((text, index) => {
      const verse = template.verses[index % template.verses.length](text)
      return {
        rank: ranks[index % ranks.length],
        verse,
        title: template.title(text),
        description: template.desc(text),
        duration: template.duration,
        category: template.category,
      }
    })
  })
  const usedTitle = new Set(handmade.map((slip) => slip.title))
  const usedDesc = new Set(handmade.map((slip) => slip.description))
  const usedVerse = new Set(handmade.map((slip) => slip.verse))
  const out = handmade.map((slip) => ({ ...slip }))
  const cursor = queues.map(() => 0)
  let guard = 0
  while (out.length < TOTAL && guard < 200000) {
    guard += 1
    let moved = false
    for (let index = 0; index < queues.length; index += 1) {
      if (out.length >= TOTAL) break
      const queue = queues[index]
      while (cursor[index] < queue.length) {
        const slip = queue[cursor[index]]
        cursor[index] += 1
        moved = true
        if (!acceptable(slip)) continue
        if (usedTitle.has(slip.title) || usedDesc.has(slip.description)) continue
        if (usedVerse.has(slip.verse)) continue
        usedTitle.add(slip.title)
        usedDesc.add(slip.description)
        usedVerse.add(slip.verse)
        out.push(slip)
        break
      }
    }
    if (!moved) break
  }
  if (out.length < TOTAL) {
    throw new Error(`只生成了 ${out.length} 支，模板或词库不够`)
  }
  return out.slice(0, TOTAL).map((slip, index) => ({
    n: index + 1,
    rank: slip.rank,
    verse: slip.verse,
    title: slip.title,
    description: slip.description,
    duration: slip.duration,
    category: slip.category,
  }))
}

